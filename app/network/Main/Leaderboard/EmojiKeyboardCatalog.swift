/**
 * The emoji-only keyboard behind the emoji tag editor. The tag is never
 * typed on the system text keyboard (android/POINTSLEADERBOARD.md): the
 * editor shows this grid instead, so nothing but emoji can be entered, and
 * the sdk still validates every tap the way the server does. The rules for
 * a tag (1 to 6 emoji, RGI sequences) live in the sdk; this is only what
