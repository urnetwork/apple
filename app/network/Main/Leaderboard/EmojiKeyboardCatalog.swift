    static let sections: [Section] = dedupe(rawSections)

    private static func dedupe(_ sections: [Section]) -> [Section] {
        var seen = Set<String>()
        return sections.map { section in
            Section(id: section.id, emoji: section.emoji.filter { seen.insert($0).inserted })
        }
    }

